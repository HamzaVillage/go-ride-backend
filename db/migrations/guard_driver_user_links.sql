-- Run via scripts/configureDriverUserLinks.js after the read-only preflight.
-- Existing conflicting records are reported separately; never reassigned automatically.
CREATE TRIGGER IF NOT EXISTS guard_driver_user_insert
BEFORE INSERT ON drivers FOR EACH ROW
BEGIN
 DECLARE linked_user INT DEFAULT NULL;
 IF NEW.User_ID_FK IS NULL OR NEW.User_ID_FK<=0 THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_REQUIRED';
 END IF;
 SELECT User_ID_Pk INTO linked_user FROM users WHERE User_ID_Pk=NEW.User_ID_FK FOR UPDATE;
 IF linked_user IS NULL THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_NOT_FOUND';
 END IF;
 IF EXISTS (SELECT 1 FROM drivers WHERE User_ID_FK=NEW.User_ID_FK) THEN
  SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_ALREADY_USED';
 END IF;
END;
-- @statement
CREATE TRIGGER IF NOT EXISTS guard_driver_user_update
BEFORE UPDATE ON drivers FOR EACH ROW
BEGIN
 DECLARE linked_user INT DEFAULT NULL;
 IF NOT (NEW.User_ID_FK <=> OLD.User_ID_FK) THEN
  IF NEW.User_ID_FK IS NULL OR NEW.User_ID_FK<=0 THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_REQUIRED';
  END IF;
  SELECT User_ID_Pk INTO linked_user FROM users WHERE User_ID_Pk=NEW.User_ID_FK FOR UPDATE;
  IF linked_user IS NULL THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_NOT_FOUND';
  END IF;
  IF EXISTS (SELECT 1 FROM drivers WHERE User_ID_FK=NEW.User_ID_FK AND id<>OLD.id) THEN
   SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='DRIVER_USER_LINK_ALREADY_USED';
  END IF;
 END IF;
END;
